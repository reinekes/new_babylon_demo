test('the courtyard camera moves only on request and checks the current house identity',()=>{
 const {window}=new JSDOM('<main></main>');
 const root=window.document.querySelector('main'),moves=[];
 const home={type:'house',x:4,y:5,waterEntityId:7};
 const s={buildings:[home],citizens:[],blessingDiscovery:{qualifiedAt:null}};
 const scene=createBlessingPresentation(root,{focus:point=>moves.push(point)});
 scene.reset(s);
 s.blessingDiscovery={qualifiedAt:1,cup:{home:'4,5',homeId:7}};
 scene.tick(s,250);
 const button=root.querySelector('[data-blessing-focus]');
 assert.equal(button.hidden,false);
 assert.deepEqual(moves,[]);
 button.click();
 assert.deepEqual(moves,[home]);
 s.buildings[0]={...home,waterEntityId:8};
 button.click();
 assert.deepEqual(moves,[home]);
 scene.tick(s,250);
 assert.equal(button.hidden,true);
 window.close();
});

test('a saved opening that has not started plays after reload and is consumed once',()=>{
 const {window}=new JSDOM('<main></main>');
 const root=window.document.querySelector('main'),s={blessingDiscovery:{qualifiedAt:5,cup:{home:'4,5',homeId:7},openingPending:true}};
 let starts=0;
 const scene=createBlessingPresentation(root,{onOpening:city=>{delete city.blessingDiscovery.openingPending;starts++;}});
 scene.reset(s);
 scene.tick(s,250,{allowOpening:false});
 assert.equal(starts,0);
 scene.tick(s,250);
 assert.equal(starts,1);
 assert.equal(root.querySelector('section').hidden,false);
 scene.reset(structuredClone(s));
 scene.tick(s,250);
 assert.equal(starts,1);
 assert.ok(root.querySelector('section').hidden);
 window.close();
});

test('the cast reports the committed outcome, skips and does not replay on reload',()=>{
 const {window}=new JSDOM('<main></main>');
 const root=window.document.querySelector('main'),cues=[];
 const city={population:12,happiness:100};
 const scene=createBlessingPresentation(root,{cue:id=>{cues.push(id);return ()=>cues.push('stop');}});
 scene.reset(city);
 scene.cast(city,{newResidents:0,happiness:5});
 scene.tick(city,250);
 const panel=root.querySelector('section');
 assert.equal(panel.dataset.kind,'cast');
 assert.match(panel.textContent,/Довольство \+5/);
 assert.match(panel.textContent,/Новых жителей · 0/);
 assert.deepEqual(cues,['blessing']);
 panel.querySelector('button').click();
 assert.equal(panel.hidden,true);
 assert.deepEqual(cues,['blessing','stop']);
 scene.reset(structuredClone(city));
 scene.tick(city,250);
 assert.equal(panel.hidden,true);
 assert.deepEqual(city,{population:12,happiness:100});
 window.close();
});
