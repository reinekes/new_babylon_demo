import test from 'node:test';
import assert from 'node:assert/strict';
import {advanceTime,createGame,decode,encode} from '../engine.js';
import {strictScenario} from '../scenario-profiles.js';
import {canDemolish} from '../management.js';
import {launchLocalFerry,localFerryVessel,releaseDriedFish,startFishDrying} from '../river-stores.js';

test('fish stays conserved through drying, a saved ferry crossing and unloading',()=>{
 const s=createGame({start:'established',mode:'mature',scenario:strictScenario()});
 const fishing={type:'fishing',x:12,y:6,level:1,workshopStock:{output:{food:4}}};
 const from={type:'harbor',x:13,y:6,level:1,boatTender:true};
 const to={type:'harbor',x:16,y:6,level:1};
 s.buildings.push(fishing,from,to);
 advanceTime(s,.1);
 const order=s.district.jobs.find(q=>q.source==='12,6');
 assert.equal(order.remaining,4);
 const food=s.resources.food;
 const drying=startFishDrying(s,from);assert.ok(drying.ok,drying.reason);
 assert.equal(fishing.workshopStock.output.food,2);
 assert.equal(order.remaining,2);assert.equal(order.cancelled,2);
 assert.equal(s.resources.food,food);
 assert.equal(startFishDrying(s,from).ok,false);
 assert.match(canDemolish(s,from),/сушки/);
 const dryingSave=encode(s);assert.equal(encode(decode(dryingSave)),dryingSave);
 advanceTime(s,12);
 assert.equal(from.driedFish,2);assert.equal(from.fishDrying,undefined);
 to.driedFish=24;
 assert.equal(launchLocalFerry(s,from,'16,6').ok,false);
 assert.equal(from.driedFish,2);
 delete to.driedFish;
 assert.ok(launchLocalFerry(s,from,'16,6').ok);
 assert.equal(from.driedFish,undefined);assert.equal(to.driedFish,undefined);
 assert.equal(s.localFerry.amount,2);
 assert.equal(launchLocalFerry(s,from,'16,6').ok,false);
 assert.match(canDemolish(s,to),/прибытия/);
 const start=localFerryVessel(s);
 advanceTime(s,1);
 assert.notEqual(localFerryVessel(s).x,start.x);
 const raw=encode(s),loaded=decode(raw);assert.equal(encode(loaded),raw);
 advanceTime(loaded,1.01);
 assert.equal(loaded.localFerry,undefined);
 assert.equal(loaded.buildings.find(b=>b.x===16&&b.y===6).driedFish,2);
 const source=loaded.buildings.find(b=>b.x===13&&b.y===6);
 source.driedFish=2;
 const beforeRelease=loaded.resources.food;
 assert.ok(releaseDriedFish(loaded,source).ok);
 assert.equal(loaded.resources.food,beforeRelease+2);
 assert.equal(source.driedFish,undefined);
});
