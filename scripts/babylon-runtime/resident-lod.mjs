import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {MeshoptSimplifier as simplify} from 'meshoptimizer';
await simplify.ready;
const models=new URL('../../assets/art-courtyard/models/',import.meta.url);
const variants=['source-walk-male','source-walk-female','source-walk-child','source-walk-adolescent','historical-man'];
const output={};
function accessor(glb,doc,index,binaryOffset,components,read,width){
 const access=doc.accessors[index],view=doc.bufferViews[access.bufferView],stride=view.byteStride||components*width;
 const offset=binaryOffset+(view.byteOffset||0)+(access.byteOffset||0);
 if(access.sparse||view.buffer!==0)throw Error('Unsupported GLB accessor');
 return Array.from({length:access.count*components},(_,i)=>glb[read](offset+Math.floor(i/components)*stride+i%components*width));
}
for(const name of variants){
 const glb=readFileSync(new URL(name+'.glb',models)),jsonLength=glb.readUInt32LE(12),doc=JSON.parse(glb.toString('utf8',20,20+jsonLength)),binary=28+jsonLength;
 const map={};
 for(const mesh of doc.meshes){
  if(mesh.primitives.length!==1)continue;
  const primitive=mesh.primitives[0],access=doc.accessors[primitive.indices];
  if(access.count<600)continue;
  const positions=Float32Array.from(accessor(glb,doc,primitive.attributes.POSITION,binary,3,'readFloatLE',4));
  const uint=access.componentType===5125;
  if(!uint&&access.componentType!==5123)throw Error('Unsupported GLB index format');
  const indices=Uint32Array.from(accessor(glb,doc,primitive.indices,binary,1,uint?'readUInt32LE':'readUInt16LE',uint?4:2));
  const [reduced,error]=simplify.simplify(indices,positions,3,Math.floor(indices.length*.38/3)*3,.016,['LockBorder']);
  if(reduced.length>=indices.length*.80)continue;
  const bytes=Buffer.alloc(reduced.length*2);
  reduced.forEach((index,i)=>bytes.writeUInt16LE(index,i*2));
  map[mesh.name]=[positions.length/3,indices.length,bytes.toString('base64')];
  console.log(name,mesh.name,indices.length/3,reduced.length/3,error);
 }
 output[name]={hash:createHash('sha256').update(glb).digest('hex').slice(0,12),meshes:map};
}
writeFileSync(new URL('../../game3d/resident-lod-indices.js',import.meta.url),'// Generated by scripts/babylon-runtime/resident-lod.mjs.\nexport const residentLodIndices='+JSON.stringify(output)+';\n');
